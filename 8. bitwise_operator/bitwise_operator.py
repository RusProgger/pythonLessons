'''

BYTWISE OPERATOR

& Побитовое И  x & y = 0 ( 0000 0000)

| Побитовое ИЛИ x | y = 14 ( 0000 1110) 

~ Побитовое НЕ ~x = -11 ( 1111 0101) 

^ Побитовое XOR x ^ y = 14 ( 0000 1110) 

>> Побитовый сдвиг вправо x >> 2 = 2 ( 0000 0010) 

<< Побитовый сдвиг влево x << 2 = 42 ( 0010 1000) 

'''


a = 10
b = 4

print(f"Вывод побитовый 'И': {a & b}")
print(f"Вывод побитовый 'Или': {a | b}")
print(f"Вывод побитовый 'Не': {~a}")
print(f"Вывод побитовый 'XOR': {a ^ b}")
print(f"Вывод побитовый 'сдвиг вправо': {a >> b}")
print(f"Вывод побитовый 'сдвиг влево': {a << b}")