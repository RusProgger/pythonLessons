# проверка возраста

name = input("Как вас зовут: ").strip()
age_user = int(input("Введите ваш возраст: "))

if age_user >= 18:
    print(f"Привет, {name}")
    print(f"Ты совершеннолетний.")
else:
    print(f"Вход запрещен! Тебе нет 18 лет. Для совершеннолетия тебе не хватает {18 - age_user} лет.")