# Задача №3 — проверка пароля.

'''

Напиши программу, которая:

Просит пользователя придумать пароль.

Если пароль равен python123 — выводит «Доступ разрешён».

Если пароль неправильный — «Неверный пароль».

Если пароль пустой — «Пароль не может быть пустым».

Дополнительное условие: если пароль короче 6 символов, вывести предупреждение.

'''

password_user = input("Введите пароль: ")

if password_user == 'python123':
    print("Доступ разрешён!")

elif password_user == '':
    print("Пароль не может быть пустым")

elif len(password_user) < 6:
    print("Пароль слишком короткий!")

else:
    print("Неверный пароль!")