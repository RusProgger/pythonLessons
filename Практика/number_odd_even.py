# Определитель чисел

'''

Напиши программу, которая просит пользователя ввести число.

Она должна определить:

Число положительное или отрицательное.

Равно ли оно нулю.

Чётное оно или нечётное.

'''

number = int(input("Введите число: "))

if number > 0:
    print("Число положительное!")
    if (number % 2 == 0):
        print("Число четное!")
    else:
        print("Число нечётное!")

elif number == 0:
    print("Число равно нулю.")

else:
    print("Число отрицательное!")
    if (number % 2 == 0):
        print("Число четное!")
    else:
        print("Число нечётное!")