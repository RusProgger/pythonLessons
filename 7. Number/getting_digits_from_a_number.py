# Getting digits from a number (Получение цифр из числа)

# Получаем последнюю цифру числа:

print(4321 % 10)  # 1
print(432 % 10)   # 2
print(43 % 10)    # 3
print(4 % 10)     # 4

# Для получения последней цифры используется операция % 10. Если число состоит из одной цифры, то операция % 10 будет давать в результате само число. Для получения нескольких последних чисел, используйте другие числа кратные 10, например, % 100, % 1000 и более.

print("\n--------------------------------\n")

print(4321 % 10)      # 1     получили последнюю цифру
print(4321 % 100)     # 21    получили 2 последних числа, начиная с десятков
print(4321 % 1000)    # 321   получили 3 последних числа, начиная с сотен
print(4321 % 10000)   # 4321  получили 4 последних числа, то есть всё число
print(4321 % 100000)  # 4321  дальше будет всё время выдавать число 4321

# Получение числа без последних цифр с помощью //

print("\n--------------------------------\n")

print(4321 // 10)  # 432
print(432 // 10)   # 43
print(43 // 10)    # 4
print(4 // 10)     # 0


# Для получения чисел без нескольких последних цифр, можно использовать // 100, // 1000 и более.

print("\n--------------------------------\n")

print(4321 // 10)     # 432
print(4321 // 100)    # 43
print(4321 // 1000)   # 4
print(4321 // 10000)  # 0


